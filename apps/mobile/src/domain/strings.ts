export function appStrings(language: LanguagePreference) {
  if (appLocale(language) === 'zh-CN') return ZH;
  return EN;
}

/** Resolve system locale without persisting or changing the user's preference. */
export function appLocale(language: LanguagePreference): 'zh-CN' | 'en-US' {
  if (language === 'zh-Hans') return 'zh-CN';
  if (language === 'en') return 'en-US';
  return Intl.DateTimeFormat().resolvedOptions().locale.toLowerCase().startsWith('zh') ? 'zh-CN' : 'en-US';
}

/** Translate only generated structural labels, never user or cloud-authored copy. */
export function momentLabel(label: string | undefined, language: LanguagePreference) {
  if (!label || appLocale(language) !== 'zh-CN') return label;
  return label.replace(/^Moment (\d+)(?: · (Motion|Photo))?$/, (_, n, kind) =>
    `片段 ${n}${kind ? kind === 'Motion' ? ' · 视频' : ' · 照片' : ''}`);
}
