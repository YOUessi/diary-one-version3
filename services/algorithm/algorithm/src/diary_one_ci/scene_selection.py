def policy_for(kind):
    key = kind if kind in POLICIES else 'UNCERTAIN'
    return {'experience_kind': key, 'policy_version': POLICY_VERSION, **deepcopy(POLICIES[key])}


def selection_policy_context():
    return {'version': POLICY_VERSION, 'common_rules': list(COMMON_RULES),
            'policies': {kind: policy_for(kind) for kind in EXPERIENCE_KINDS}}


